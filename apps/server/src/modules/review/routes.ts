import type { FastifyInstance, FastifyRequest } from 'fastify';
import { ULID_RE } from '@t-cli/core/ulid';
import { z } from 'zod';
import type { AppDeps } from '../../deps.ts';
import { authOf, requireAuth } from '../../http/auth.ts';
import { AppError, loggableError, notFound, ok } from '../../http/errors.ts';
import { createRateLimiter } from '../../lib/rateLimit.ts';
import { pushReviewLogs, suspendItemOfCard, undoReviewLog, type IncomingLog, type PushRejection } from './cards.ts';
import { enforceRateLimit, IdParams, MINUTE_MS, UtcOffsetMinutes } from './common.ts';
import { RATING_VALUES, type RatingValue } from './fsrs.ts';
import { reviewQueue, reviewSummary, type ReviewLimits } from './queue.ts';

export const PUSH_MAX_LOGS = 200;
export const QUEUE_MAX_LIMIT = 100;
/** A rating can be undone this long after the server accepted it. */
export const UNDO_WINDOW_MS = 5 * MINUTE_MS;
/** Ratings further than this in the future (client clock skew) are rejected. */
export const FUTURE_TOLERANCE_MS = 5 * MINUTE_MS;
export const REPORTS_PER_MINUTE = 10;
const DURATION_MAX_MS = 86_400_000;

const SummaryQuery = z.object({ utcOffsetMinutes: UtcOffsetMinutes });
const QueueQuery = z.object({
  utcOffsetMinutes: UtcOffsetMinutes,
  limit: z.coerce.number().int().min(1).max(QUEUE_MAX_LIMIT).default(50),
});
const PushBody = z.object({ logs: z.array(z.unknown()).min(1).max(PUSH_MAX_LOGS) });
const LogShape = z.object({
  id: z.string().regex(ULID_RE, 'must be a ULID'),
  cardId: z.string().min(1).max(64),
  rating: z.number().int().refine((value) => RATING_VALUES.includes(value as RatingValue), 'must be 1, 2, 3 or 4'),
  reviewedAt: z.iso.datetime({ offset: true }),
  durationMs: z.number().int().min(0).max(DURATION_MAX_MS).nullish(),
});

const idOf = (value: unknown): string | null =>
  value && typeof value === 'object' && 'id' in value && typeof value.id === 'string' ? value.id : null;

/** Validate each raw log; a bad one is rejected on its own, never the batch (as entry pushes). */
function partitionLogs(raw: readonly unknown[], now: Date): { valid: IncomingLog[]; rejected: PushRejection[] } {
  const valid: IncomingLog[] = [];
  const rejected: PushRejection[] = [];
  for (const value of raw) {
    const parsed = LogShape.safeParse(value);
    if (!parsed.success) {
      rejected.push({ id: idOf(value), errors: parsed.error.issues.map((issue) => `${issue.path.join('.') || 'log'}: ${issue.message}`) });
      continue;
    }
    const reviewedAt = new Date(parsed.data.reviewedAt);
    if (reviewedAt.getTime() > now.getTime() + FUTURE_TOLERANCE_MS) {
      rejected.push({ id: parsed.data.id, errors: ['reviewedAt: is in the future'] });
      continue;
    }
    valid.push({
      id: parsed.data.id,
      cardId: parsed.data.cardId,
      rating: parsed.data.rating as RatingValue,
      reviewedAt,
      durationMs: parsed.data.durationMs ?? null,
    });
  }
  return { valid, rejected };
}

/**
 * Review (docs/api-v1.md, "Review"):
 *   GET    /v1/review/summary      the 复习 tab: due count, limits, streak
 *   GET    /v1/review/queue        cards to review now, with interval previews
 *   POST   /v1/reviews             push ratings (idempotent batch)
 *   DELETE /v1/reviews/:id         undo a rating within 5 minutes
 *   POST   /v1/cards/:id/report    "内容有误": suspend the item and regenerate it
 *
 * Logs carry ids, counts and outcomes only.
 */
export async function registerReviewRoutes(app: FastifyInstance, deps: AppDeps): Promise<void> {
  const { config, db, clock } = deps;
  const authenticate = requireAuth(config.JWT_SECRET, clock, deps.db);
  const limits: ReviewLimits = { newPerDay: config.REVIEW_NEW_PER_DAY, reviewsPerDay: config.REVIEW_MAX_PER_DAY };
  const reports = createRateLimiter({ limit: REPORTS_PER_MINUTE, windowMs: MINUTE_MS });
  /** Items being regenerated by this process, so repeated reports do not start a second run. */
  const regenerating = new Set<string>();

  app.get('/v1/review/summary', { preHandler: authenticate }, async (request) => {
    const { userId } = authOf(request);
    const { utcOffsetMinutes } = SummaryQuery.parse(request.query);
    return ok(await reviewSummary(db, { userId, now: clock(), utcOffsetMinutes, limits }));
  });

  app.get('/v1/review/queue', { preHandler: authenticate }, async (request) => {
    const { userId } = authOf(request);
    const query = QueueQuery.parse(request.query);
    const cards = await reviewQueue(db, { userId, now: clock(), utcOffsetMinutes: query.utcOffsetMinutes, limits, limit: query.limit });
    request.log.info({ userId, served: cards.length }, 'review queue');
    return ok({ cards });
  });

  app.post('/v1/reviews', { preHandler: authenticate, bodyLimit: 256 * 1024 }, async (request) => {
    const { userId, deviceId } = authOf(request);
    const body = PushBody.parse(request.body);
    const now = clock();
    const { valid, rejected } = partitionLogs(body.logs, now);
    const result = await pushReviewLogs(db, { userId, deviceId, logs: valid, now, masteredDays: config.MASTERED_DAYS });
    const allRejected = [...rejected, ...result.rejected];
    request.log.info(
      { userId, pushed: body.logs.length, inserted: result.inserted, rejected: allRejected.length, cards: result.cards.length },
      'review logs pushed',
    );
    return ok({ accepted: result.accepted, rejected: allRejected, cards: result.cards });
  });

  app.delete('/v1/reviews/:id', { preHandler: authenticate }, async (request) => {
    const { userId } = authOf(request);
    const { id } = IdParams.parse(request.params);
    const outcome = await undoReviewLog(db, { userId, logId: id, now: clock(), windowMs: UNDO_WINDOW_MS, masteredDays: config.MASTERED_DAYS });
    request.log.info({ userId, logId: id, outcome: outcome.kind }, 'review undo');
    if (outcome.kind === 'not_found') throw notFound('review');
    if (outcome.kind === 'expired') throw new AppError(409, 'UNDO_EXPIRED', 'the review can no longer be undone');
    return ok({ card: outcome.card });
  });

  app.post('/v1/cards/:id/report', { preHandler: authenticate }, async (request, reply) => {
    const { userId } = authOf(request);
    const { id } = IdParams.parse(request.params);
    const now = clock();
    enforceRateLimit(reports, userId, now, reply, 'too many reports, slow down');
    const suspended = await suspendItemOfCard(db, { userId, cardId: id, now });
    if (!suspended) {
      request.log.info({ userId, cardId: id, outcome: 'not_found' }, 'card reported');
      throw notFound('card');
    }
    startRegeneration(request, userId, suspended.itemId);
    request.log.info({ userId, cardId: id, itemId: suspended.itemId, outcome: 'regenerating' }, 'card reported');
    return reply.status(202).send(ok({ regenerating: true }));
  });

  /** Fire and forget: the response does not wait; failures leave the item `needs_regen` (the regenerator alerts). */
  function startRegeneration(request: FastifyRequest, userId: string, itemId: string): void {
    const key = `${userId}:${itemId}`;
    if (regenerating.has(key)) return;
    regenerating.add(key);
    const startedAt = Date.now();
    void Promise.resolve()
      .then(() => deps.regenerator.regenerate(userId, itemId))
      .then(
        () => request.log.info({ userId, itemId, ms: Date.now() - startedAt, outcome: 'ok' }, 'item regeneration'),
        (error: unknown) => request.log.warn({ userId, itemId, ms: Date.now() - startedAt, outcome: 'failed', ...loggableError(error) }, 'item regeneration'),
      )
      .finally(() => regenerating.delete(key));
  }
}
